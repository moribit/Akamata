#!/usr/bin/env python3
"""Derive all-round medians from retained v0.2.1 evidence, without rerunning load."""
import argparse
import json
import statistics
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("directory", nargs="?", default="benchmark-results/v0.2.1")
args = parser.parse_args()
directory = Path(args.directory)
summary = {}
for name in ("final-paired", "paired-allocations", "paired-observability",
             "paired-metrics-allocations", "paired-large-json", "paired-short-lived",
             "db-contention-repeat", "tail-repeat", "paired-high-observability", "capacity-headroom"):
    path = directory / (name + ".json")
    if not path.exists():
        continue
    data = json.loads(path.read_text())
    groups = {}
    for run in data["runs"]:
        key = (run["label"], run["kind"], run["connections"], run.get("endpoint"))
        groups.setdefault(key, []).append(run)
    rows = []
    for (label, kind, connections, endpoint), runs in groups.items():
        row = {"label": label, "kind": kind, "connections": connections,
               "endpoint": endpoint, "rounds": len(runs)}
        for field in ("cpu_percent", "rss_mean_kib", "threads_peak", "shutdown_ms"):
            if all(field in run for run in runs):
                row[field] = statistics.median(run[field] for run in runs)
        if kind != "idle":
            def succeeded(run):
                return run["oha"]["statusCodeDistribution"].get("200", 0)
            row["http_200_per_second"] = statistics.median(
                succeeded(run) / run["oha"]["summary"]["total"] for run in runs)
            row["transport_success_rate"] = statistics.median(
                run["oha"]["summary"]["successRate"] for run in runs)
            row["http_status_codes"] = sorted({code for run in runs for code in run["oha"]["statusCodeDistribution"]})
            row["errors"] = sorted({error for run in runs for error in run["oha"]["errorDistribution"]})
            for percentile in ("p50", "p95", "p99"):
                row[percentile + "_ms"] = statistics.median(
                    1000 * run["oha"]["latencyPercentiles"][percentile] for run in runs)
            row["process_cpu_us_per_http_200"] = statistics.median(
                run["cpu_percent"] / 100 * run["oha"]["summary"]["total"] * 1e6 / succeeded(run)
                for run in runs if succeeded(run))
            if all("allocator" in run for run in runs):
                for metric in ("calls", "requested"):
                    row["backing_" + metric + "_per_http_200"] = statistics.median(
                        run["allocator"][metric] / succeeded(run) for run in runs if succeeded(run))
                row["allocator_live_final"] = [run["allocator"]["live"] for run in runs]
        rows.append(row)
    summary[name] = {"binaries": data["binaries"], "rows": rows}
(directory / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
text = ["# Paired all-round medians", "", "Generated by `python3 tools/bench/v021_summary.py`.", "",
        "HTTP 200/second; successful-response latency in ms. CPU is process CPU %, RSS in KiB. "
        "Three rounds per HTTP group, one sample per idle group. These are short local snapshots, not capacity certification.", ""]
for name, data in summary.items():
    text += ["## " + name, "", "| Label | Connections | Endpoint | HTTP 200/s | P50 ms | P95 ms | P99 ms | CPU % | RSS KiB |", "|---|---:|---|---:|---:|---:|---:|---:|---:|"]
    for row in data["rows"]:
        if row["kind"] == "idle":
            continue
        text.append("| {label} | {connections} | {endpoint} | {http_200_per_second:,.0f} | {p50_ms:.3f} | {p95_ms:.3f} | {p99_ms:.3f} | {cpu_percent:.1f} | {rss_mean_kib:,.0f} |".format(**row))
    text.append("")
(directory / "comparison.md").write_text("\n".join(text) + "\n")
print("Derived", len(summary), "datasets; all rounds retained.")
